#!/usr/bin/env python3
"""Builds src/lua/WizardChunk.h: Wizard (wizard.kimmy) compiled to Lua 5.1
bytecode without debug information (luac5.1 -s), then scrambled so the
strings it holds do not show in dirk.exe. dirk --wizard <folder> runs it
(see wizardChunk() in src/lua/LuaEngine.cpp). The bytecode is the same for
every 64-bit little-endian build (Windows x64, Linux x86_64 and arm64).

    python3 tools/embed_wizard.py <wizard.kimmy> src/lua/WizardChunk.h [luac5.1]
"""
import hashlib, os, subprocess, sys, tempfile

def main():
    src, dst = sys.argv[1], sys.argv[2]
    luac = sys.argv[3] if len(sys.argv) > 3 else 'luac5.1'
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'w.luac')
        subprocess.run([luac, '-s', '-o', out, src], check=True)
        code = open(out, 'rb').read()
    if code[:5] != b'\x1bLuaQ':
        sys.exit('not Lua 5.1 bytecode')
    x = 0x2545F491
    data = bytearray()
    for b in code:
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        data.append(b ^ ((x >> 16) & 0xFF))
    tag = hashlib.md5(open(src, 'rb').read()).hexdigest()[:8]
    lines = ['// Generated by tools/embed_wizard.py from wizard.kimmy %s -- do not edit.' % tag,
             '#pragma once', '#include <cstddef>', 'namespace dirk {',
             'static const char kWizardTag[] = "%s";' % tag,
             'static const std::size_t kWizardChunkSize = %d;' % len(data),
             'static const unsigned char kWizardChunk[] = {']
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + 20]) + ',')
    lines += ['};', '} // namespace dirk', '']
    open(dst, 'w', newline='\n').write('\n'.join(lines))
    print('%s: %d bytes of bytecode (wizard.kimmy %s)' % (dst, len(data), tag))

main()
