#!/usr/bin/env python3
# Regenerates src/core/Languages.cpp from the ISO 639 tables (pip package
# "pycountry"). Run from the repo root: python3 tools/gen_languages.py
import pycountry

# Menu names: shorter than the ISO reference names, ASCII only.
OVERRIDES = {
    'el': 'Greek', 'ia': 'Interlingua', 'ms': 'Malay', 'ne': 'Nepali', 'nb': 'Norwegian Bokmal',
    'oc': 'Occitan', 'or': 'Oriya', 'sw': 'Swahili', 'to': 'Tongan', 'vo': 'Volapuk',
    'pa': 'Punjabi', 'ps': 'Pashto', 'ug': 'Uyghur', 'ky': 'Kyrgyz', 'dv': 'Dhivehi',
    'cu': 'Church Slavonic', 'li': 'Limburgish', 'ht': 'Haitian Creole',
}

rows = []
for l in pycountry.languages:
    if hasattr(l, 'alpha_2'):
        name = OVERRIDES.get(l.alpha_2, l.name)
        assert name.isascii() and len(name) <= 18, (l.alpha_2, name)
        rows.append((l.alpha_2, l.alpha_3, getattr(l, 'bibliographic', '') or '', name))
rows.sort()
body = '\n'.join(f'    {{"{a}", "{t}", "{b}", "{n}"}},' for a, t, b, n in rows)

open('src/core/Languages.cpp', 'w').write(f'''// GENERATED by tools/gen_languages.py -- edit that script, not this table.
#include "core/Languages.h"

#include <cctype>

namespace dirk {{

namespace {{

struct Language {{
    const char* code1;  // ISO 639-1
    const char* code2t; // ISO 639-2/T (also ISO 639-3)
    const char* code2b; // ISO 639-2/B when it differs ("fre" for French), else ""
    const char* name;   // English, ASCII only (any game font can show it)
}};

// Every ISO 639-1 language ({len(rows)}). English names, shortened for the
// menu ("Modern Greek (1453-)" -> "Greek") and ASCII ("Volapuk").
const Language kLanguages[] = {{
{body}
}};

std::string lowerAscii(const std::string& s) {{
    std::string out = s;
    for (char& c : out) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return out;
}}

const Language* find(const std::string& code) {{
    const std::string c = lowerAscii(code);
    if (c.size() == 2) {{
        // "jp" is not ISO 639-1 (it is Japan's country code) but it is the
        // usual mistake for Japanese in file names ("-jp.ogg"); accepted
        // since the first multi-language version.
        const std::string key = (c == "jp") ? "ja" : c;
        for (const Language& l : kLanguages) if (key == l.code1) return &l;
    }} else if (c.size() == 3) {{
        for (const Language& l : kLanguages) if (c == l.code2t || c == l.code2b) return &l;
    }}
    return nullptr;
}}

}} // namespace

std::string languageName(const std::string& tag) {{
    if (tag.empty()) return "";
    // "pt-br", "pt_BR", "fr-ca": the language, then a region.
    const size_t sep = tag.find_first_of("-_");
    const Language* l = find(tag.substr(0, sep));
    if (!l) return "Unknown";
    std::string name = l->name;
    if (sep != std::string::npos) {{
        const std::string region = tag.substr(sep + 1);
        if (region.empty() || region.size() > 4 || region.find_first_of("-_") != std::string::npos) return "Unknown";
        std::string up = region;
        for (char& c : up) c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
        name += " (" + up + ")";
    }}
    return name;
}}

bool isKnownLanguageCode(const std::string& code) {{
    return find(code) != nullptr;
}}

const char* iso639_2Code(const std::string& tag) {{
    const Language* l = find(tag.substr(0, tag.find_first_of("-_")));
    if (!l) return nullptr;
    return l->code2b[0] ? l->code2b : l->code2t; // Matroska uses the /B codes
}}

namespace {{
// "FR", "ita", "pt-BR", "en_us": two or three letters, maybe a region.
bool looksLikeCode(const std::string& s) {{
    const size_t sep = s.find_first_of("-_");
    const std::string lang = s.substr(0, sep);
    if (lang.size() < 2 || lang.size() > 3) return false;
    for (unsigned char c : lang) if (!std::isalpha(c)) return false;
    if (sep == std::string::npos) return true;
    const std::string region = s.substr(sep + 1);
    if (region.empty() || region.size() > 4) return false;
    for (unsigned char c : region) if (!std::isalnum(c)) return false;
    return true;
}}
}} // namespace

std::string audioStreamLabel(const std::string& title, const std::string& language, bool firstTrack) {{
    const std::string lang = lowerAscii(language);
    const bool hasLang = !lang.empty() && lang != "und";
    if (hasLang) {{
        const std::string n = languageName(lang);
        if (n != "Unknown") return n;
    }}
    if (!title.empty()) {{
        if (looksLikeCode(title)) return languageName(title);
        if (title.size() <= 20) return title;
    }}
    if (hasLang) return "Unknown";
    return firstTrack ? "Original" : "Unknown";
}}

void makeLabelsUnique(std::vector<std::string>& labels) {{
    const std::vector<std::string> original = labels;
    for (size_t i = 1; i < labels.size(); ++i) {{
        int n = 1;
        for (size_t j = 0; j < i; ++j) if (original[j] == original[i]) ++n;
        if (n > 1) labels[i] += " (" + std::to_string(n) + ")";
    }}
}}

}} // namespace dirk
''')
print(len(rows), 'languages')
